#!/bin/sh
# Stage the host's agent configuration into ./config for the container.
#
# The container never mounts the host's home directory: it reads copies from
# ./config (mounted read-only at /config). This script produces those copies,
# with the one invariant the container relies on -- everything in ./config
# except engine.env is world-readable, so the image's own user can read it
# without any UID/GID matching.
#
# ./config is never committed (it is git-ignored): it holds copies of the
# operator's own credentials, settings, skills and git identity, so this
# script is what creates it. Nothing here is shipped as an example.
#
# Usage:
#   docker/config-sync.sh              copy config and report what changed
#   docker/config-sync.sh --check      report drift only, exit 1 if different
#   docker/config-sync.sh --no-auth    do not copy pi/auth.json
#   docker/config-sync.sh --no-skills  do not copy pi/skills
#
# Re-running is safe and is the supported way to apply changes: config is
# authoritative at container start, so `docker compose restart` picks it up.
set -eu

REPO_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
CONFIG_DIR="${CONFIG_DIR:-${REPO_ROOT}/config}"
PI_HOME="${HOME}/.pi/agent"
# Container paths. They must match the volume mounts in docker-compose.yml;
# tests/test_docker.py fails when they drift.
WORKSPACE_ROOT_PATH=/home/agent/agents
DATA_DIR_PATH=/home/agent/.local/share/op-agent-engine
ENGINE_CONFIG_PATH=/config/workflow.yaml

CHECK=0
COPY_AUTH=1
COPY_SKILLS=1

for arg in "$@"; do
  case "$arg" in
    --check) CHECK=1 ;;
    --no-auth) COPY_AUTH=0 ;;
    --no-skills) COPY_SKILLS=0 ;;
    -h|--help) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '%s\n' "$*"; }
changed=0
missing=0

# True when the destination tree already matches a dereferenced copy of the
# source. Skills are often symlinks into a shared directory, so the source is
# dereferenced before comparing (a dangling symlink inside the container would
# be useless anyway).
tree_same() {
  src=$1
  dst=$2
  [ -d "$dst" ] || return 1
  tmp=$(mktemp -d) || return 1
  if cp -aL "${src}/." "${tmp}/" 2>/dev/null && diff -r "$tmp" "$dst" >/dev/null 2>&1; then
    rm -rf "$tmp"
    return 0
  fi
  rm -rf "$tmp"
  return 1
}

# Copy one file and report whether the destination changed. Never writes in
# --check mode.
copy_file() {
  src=$1
  dst=$2
  if [ ! -f "$src" ]; then
    say "missing:   $src (skipped)"
    missing=1
    return 0
  fi
  if [ -f "$dst" ] && cmp -s "$src" "$dst"; then
    [ "$CHECK" -eq 0 ] && chmod 0644 "$dst"
    say "unchanged: ${dst#"$REPO_ROOT"/}"
    return 0
  fi
  changed=1
  if [ "$CHECK" -eq 1 ]; then
    say "outdated:  ${dst#"$REPO_ROOT"/}"
    return 0
  fi
  mkdir -p "$(dirname "$dst")"
  cp "$src" "$dst"
  chmod 0644 "$dst"
  say "updated:   ${dst#"$REPO_ROOT"/}"
}

# Copy a directory tree, replacing the destination. Never writes in --check
# mode.
copy_tree() {
  src=$1
  dst=$2
  if [ ! -d "$src" ]; then
    say "missing:   $src (skipped)"
    missing=1
    return 0
  fi
  if tree_same "$src" "$dst"; then
    [ "$CHECK" -eq 0 ] && chmod -R a+rX "$dst"
    say "unchanged: ${dst#"$REPO_ROOT"/}"
    return 0
  fi
  changed=1
  if [ "$CHECK" -eq 1 ]; then
    say "outdated:  ${dst#"$REPO_ROOT"/}"
    return 0
  fi
  rm -rf "$dst"
  mkdir -p "$dst"
  cp -aL "${src}/." "$dst/"
  chmod -R a+rX "$dst"
  say "updated:   ${dst#"$REPO_ROOT"/}"
}

# Rewrite the host-relative paths in a seeded engine.env to container paths.
rewrite_container_paths() {
  file=$1
  tmp="${file}.tmp"
  awk -v ws="$WORKSPACE_ROOT_PATH" \
      -v data="$DATA_DIR_PATH" \
      -v cfg="$ENGINE_CONFIG_PATH" '
    # The host-only instructions do not apply to the container variant.
    /^# `op-agent-engine init` substitutes <home>/       { next }
    /^# Copy to <checkout>\/engine.env/                  { next }
    /^# The installer copies it to ~\/.config/           { next }
    /^# Absolute path to the agents\/ directory/         { next }
    /^[[:space:]]*(export[[:space:]]+)?WORKSPACE_ROOT=/ { print "WORKSPACE_ROOT=" ws; next }
    /^[[:space:]]*(export[[:space:]]+)?DATA_DIR=/         { print "DATA_DIR=" data; next }
    /^[[:space:]]*(export[[:space:]]+)?ENGINE_CONFIG=/    { print "ENGINE_CONFIG=" cfg; next }
    /^[[:space:]]*(export[[:space:]]+)?DASHBOARD_HOST=/   { print "DASHBOARD_HOST=0.0.0.0"; next }
    { print }
  ' "$file" > "$tmp"
  {
    printf '%s\n' \
      "# --- generated by docker/config-sync.sh -----------------------------" \
      "# Container variant: the paths below point inside the image and match" \
      "# the volume mounts in docker-compose.yml. Keep them as they are."
    cat "$tmp"
  } > "${tmp}.new"
  mv "${tmp}.new" "$file"
  rm -f "$tmp"
  chmod 0600 "$file"
}

if [ "$CHECK" -eq 0 ]; then
  # Directory skeleton only: the operator fills these in.
  mkdir -p "${CONFIG_DIR}/pi/skills"
  say "skeleton:  ${CONFIG_DIR#"$REPO_ROOT"/}/pi/skills/"
fi

say ""
say "== operator files =="
if [ "$CHECK" -eq 0 ]; then
  if [ -f "${CONFIG_DIR}/workflow.yaml" ]; then
    say "present:   config/workflow.yaml"
  else
    cp "${REPO_ROOT}/workflow.example.yaml" "${CONFIG_DIR}/workflow.yaml"
    chmod 0644 "${CONFIG_DIR}/workflow.yaml"
    say "created:   config/workflow.yaml (edit it)"
    changed=1
  fi
  if [ -f "${CONFIG_DIR}/engine.env" ]; then
    say "present:   config/engine.env"
  else
    cp "${REPO_ROOT}/engine.env.example" "${CONFIG_DIR}/engine.env"
    rewrite_container_paths "${CONFIG_DIR}/engine.env"
    say "created:   config/engine.env (edit it: tokens, OP_BASE_URL)"
    changed=1
  fi
else
  for f in workflow.yaml engine.env; do
    [ -f "${CONFIG_DIR}/${f}" ] || { say "missing:   config/${f}"; missing=1; }
  done
fi

say ""
say "== agent configuration from ${PI_HOME} =="
copy_file "${PI_HOME}/settings.json" "${CONFIG_DIR}/pi/settings.json"
if [ ! -f "${HOME}/.gitconfig" ]; then
  say "warning:   no ~/.gitconfig -- agents cannot commit; set user.name/user.email"
fi
copy_file "${HOME}/.gitconfig" "${CONFIG_DIR}/gitconfig"
if [ "$COPY_AUTH" -eq 1 ]; then
  copy_file "${PI_HOME}/auth.json" "${CONFIG_DIR}/pi/auth.json"
else
  say "skipped:   pi/auth.json (--no-auth: supply provider keys via engine.env)"
fi
if [ "$COPY_SKILLS" -eq 1 ]; then
  copy_tree "${PI_HOME}/skills" "${CONFIG_DIR}/pi/skills"
else
  say "skipped:   pi/skills (--no-skills)"
fi

if [ "$CHECK" -eq 1 ]; then
  if [ "$changed" -eq 1 ] || [ "$missing" -eq 1 ]; then
    say ""
    say "config/ is out of date; run docker/config-sync.sh and restart"
    exit 1
  fi
  say ""
  say "config/ matches the host"
  exit 0
fi

say ""
say "config/ is not committed: it holds your own credentials, settings,"
say "skills and git identity. Nothing else is needed from the repository."
say ""
say "next: docker compose pull && docker compose up -d"
say "      (after editing config/engine.env: docker compose up -d)"
